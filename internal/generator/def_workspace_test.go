func TestGeneratePermissionDeclarations_RegeneratesExistingFile(t *testing.T) {
	dir := t.TempDir()
	if err := os.MkdirAll(filepath.Join(dir, "defs", "permissions"), 0755); err != nil {
		t.Fatalf("mkdir permission defs: %v", err)
	}
	if err := os.WriteFile(filepath.Join(dir, "go.work"), []byte("go 1.24.1\n"), 0644); err != nil {
		t.Fatalf("write go.work: %v", err)
	}
	appDir := filepath.Join(dir, "apps", "hrise-admin-api")
	if err := os.MkdirAll(appDir, 0755); err != nil {
		t.Fatalf("mkdir app: %v", err)
	}
	if err := os.WriteFile(filepath.Join(appDir, "go.mod"), []byte("module github.com/KOMKZ/hrise-server-app/apps/hrise-admin-api\n"), 0644); err != nil {
		t.Fatalf("write go.mod: %v", err)
	}

	defContent := `
domain: admin
permissions:
  - code: admin:read
    name: View admins
    type: read
    group: SYSTEM
    apis:
      - {method: get, path: /api/admins/page}
`
	if err := os.WriteFile(filepath.Join(dir, "defs", "permissions", "admin.yaml"), []byte(defContent), 0644); err != nil {
		t.Fatalf("write permission def: %v", err)
	}

	outPath := filepath.Join(dir, "domains", "admin", "permissions", "declared_permissions.go")
	if err := os.MkdirAll(filepath.Dir(outPath), 0755); err != nil {
		t.Fatalf("mkdir permissions: %v", err)
	}
	original := []byte("package permissions\n\nvar Stale = true\n")
	if err := os.WriteFile(outPath, original, 0644); err != nil {
		t.Fatalf("write existing file: %v", err)
	}

	warnings, err := GeneratePermissionDeclarations(dir, "admin", apiTemplates, "templates/api")
	if err != nil {
		t.Fatalf("GeneratePermissionDeclarations() err = %v", err)
	}
	if len(warnings) != 0 {
		t.Fatalf("warnings len = %d, want 0", len(warnings))
	}
	got, err := os.ReadFile(outPath)
	if err != nil {
		t.Fatalf("read output: %v", err)
	}
	text := string(got)
	if text == string(original) {
		t.Fatalf("existing file was not regenerated")
	}
	if !strings.Contains(text, "Code generated by ygctl from defs/permissions/*.yaml; DO NOT EDIT.") {
		t.Fatalf("missing generated header: %q", text)
	}
	if !strings.Contains(text, `PermissionCode: "admin:read"`) {
		t.Fatalf("missing generated permission: %q", text)
	}
}

