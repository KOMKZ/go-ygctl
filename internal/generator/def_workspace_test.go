func TestBuildDeclaredPermissionData_EmitsAPIPolicies(t *testing.T) {
	data := buildDeclaredPermissionData("github.com/KOMKZ/hrise-server-app", PermissionDef{
		Domain: "admin",
		Permissions: []PermissionDefItem{
			{
				Code:  "admin:read",
				Name:  "View admins",
				Type:  "READ",
				Group: "SYSTEM",
				APIs: []PermissionAPI{
					{Method: "GET", Path: "/api/admins/page"},
				},
			},
		},
	})
	if len(data.Permissions) != 1 {
		t.Fatalf("permissions len = %d, want 1", len(data.Permissions))
	}
	if len(data.Policies) != 1 {
		t.Fatalf("policies len = %d, want 1", len(data.Policies))
	}
	if data.Policies[0].Path != "/api/admins/page" {
		t.Fatalf("policy path = %q, want api path", data.Policies[0].Path)
	}
}
